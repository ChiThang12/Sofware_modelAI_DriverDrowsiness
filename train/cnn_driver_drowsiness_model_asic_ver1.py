# STEP 5 (SỬA LẠI): BUILD MODEL — fix BN range issue từ diagnostic
# ═══════════════════════════════════════════════════════════════════════════
#
# Vấn đề từ diagnostic:
#   - BN layers có range 17–25 → int8 resolution chỉ ~0.1/step → mất thông tin
#   - conv4_proj range 25.08 (worst), output range 23.16
