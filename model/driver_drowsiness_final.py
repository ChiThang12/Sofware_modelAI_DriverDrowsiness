def build_asic_model(input_shape=(IMG_SIZE, IMG_SIZE, 1)):
    inputs = tf.keras.Input(shape=input_shape, name="input_q07")

    # Block 1: 128×128 → 64×64
    x = tf.keras.layers.SeparableConv2D(32, 3, padding='same', use_bias=False, name='conv1')(inputs)
    x = tf.keras.layers.BatchNormalization(name='bn1')(x)
    x = tf.keras.layers.ReLU(name='relu1')(x)
    x = tf.keras.layers.MaxPooling2D(2, name='pool1')(x)

    # Block 2: 64×64 → 32×32
    x = tf.keras.layers.SeparableConv2D(64, 3, padding='same', use_bias=False, name='conv2')(x)
    x = tf.keras.layers.BatchNormalization(name='bn2')(x)
    x = tf.keras.layers.ReLU(name='relu2')(x)
    x = tf.keras.layers.MaxPooling2D(2, name='pool2')(x)

    # Block 3: 32×32 → 16×16
    x = tf.keras.layers.SeparableConv2D(128, 3, padding='same', use_bias=False, name='conv3')(x)
    x = tf.keras.layers.BatchNormalization(name='bn3')(x)
    x = tf.keras.layers.ReLU(name='relu3')(x)
    x = tf.keras.layers.MaxPooling2D(2, name='pool3')(x)

    # Block 4: 16×16 (deep features)
    x = tf.keras.layers.SeparableConv2D(128, 3, padding='same', use_bias=False, name='conv4')(x)
    x = tf.keras.layers.BatchNormalization(name='bn4')(x)
    x = tf.keras.layers.ReLU(name='relu4')(x)

    # Head
    x = tf.keras.layers.GlobalAveragePooling2D(name='gap')(x)
    x = tf.keras.layers.Dense(32, use_bias=True, name='fc1')(x)
    x = tf.keras.layers.ReLU(name='relu_fc')(x)
    x = tf.keras.layers.Dense(1, use_bias=True, name='output')(x)

    model = tf.keras.Model(inputs, x, name="drowsiness_asic")
    return model


