def extract_weights_for_asic(tflite_path, output_dir):
    interp = tf.lite.Interpreter(model_path=tflite_path)
    interp.allocate_tensors()

    lines = [
        "// ============================================================",
        "// AUTO-GENERATED — ASIC Weight File",
        f"// Source: {os.path.basename(tflite_path)}",
        "// ============================================================",
        "",
        "#ifndef ASIC_WEIGHTS_H",
        "#define ASIC_WEIGHTS_H",
        "",
        "#include <stdint.h>",
        "",
    ]

    for t in interp.get_tensor_details():
        qp = t["quantization_parameters"]
        try:
            data = interp.get_tensor(t["index"])
        except Exception:
            continue

        if data is None:
            continue

        safe_name = (
            t["name"]
            .replace("/", "_")
            .replace(":", "_")
            .replace(".", "_")
        )

        if data.dtype == np.int8 and len(qp["scales"]) > 0:
            flat = data.flatten()
            data_str = ", ".join(str(int(v)) for v in flat)
            lines += [
                f"// Tensor index {t['index']}, shape = {data.shape}",
                f"const int8_t {safe_name}[{len(flat)}] = {{",
                f"    {data_str}",
                "};",
                "",
            ]
            scales = qp["scales"]
            scales_str = ", ".join(f"{s:.10f}f" for s in scales)
            lines += [
                f"const float {safe_name}_scale[{len(scales)}] = {{",
                f"    {scales_str}",
                "};",
                "",
            ]

        elif data.dtype == np.int32:
            flat = data.flatten()
            data_str = ", ".join(str(int(v)) for v in flat)
            lines += [
                f"// Bias tensor index {t['index']}, shape = {data.shape}",
                f"const int32_t {safe_name}[{len(flat)}] = {{",
                f"    {data_str}",
                "};",
                "",
            ]

    lines.append("#endif  // ASIC_WEIGHTS_H")

    os.makedirs(output_dir, exist_ok=True)
    output_path = os.path.join(output_dir, "asic_weights.h")
    with open(output_path, "w") as f:
        f.write("\n".join(lines))

    print(f"✅ ASIC header generated: {output_path}")
    return output_path

