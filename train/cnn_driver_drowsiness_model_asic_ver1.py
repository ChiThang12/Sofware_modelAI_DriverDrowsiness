# Fix:
#   1. Đổi thứ tự: Conv → BN → ReLU6  (hiện tại: Conv → ReLU6 → BN cho một số layer)
#      ReLU6 clamp ở 6 → BN output bị giới hạn [-6, 6] → range giảm từ 25 xuống ~6
#   2. conv4_proj: thêm ReLU6 sau BN để clamp range
#   3. output layer: KHÔNG quantize → giữ float32, sigmoid tính ngoài

def build_asic_model(input_shape=(64, 64, 1)):
    inputs = tf.keras.Input(shape=input_shape, name="input_q07")

    # ===== Block 0: Quantize input (ignore in full precision) =====
    x = inputs  # chỉ giữ input layer

    # ===== Block 1 ===== (64 → 32)
    x = tf.keras.layers.DepthwiseConv2D(3, padding='same', use_bias=False, name='depthwise_conv1')(x)
    x = tf.keras.layers.Conv2D(32, 1, padding='same', use_bias=False, name='conv1')(x)
    x = tf.keras.layers.BatchNormalization(name='bn1')(x)
    x = tf.keras.layers.ReLU(max_value=6, name='relu1')(x)
    x = tf.keras.layers.MaxPooling2D(2, name='pool1')(x)

    # ===== Block 2 ===== (32 → 16)
    x = tf.keras.layers.DepthwiseConv2D(3, padding='same', use_bias=False, name='depthwise_conv2')(x)
    x = tf.keras.layers.Conv2D(64, 1, padding='same', use_bias=False, name='conv2')(x)
    x = tf.keras.layers.BatchNormalization(name='bn2')(x)
    x = tf.keras.layers.ReLU(max_value=6, name='relu2')(x)
    x = tf.keras.layers.MaxPooling2D(2, name='pool2')(x)

    # ===== Block 3 ===== (16 → 8)
    x = tf.keras.layers.DepthwiseConv2D(3, padding='same', use_bias=False, name='depthwise_conv3')(x)
    x = tf.keras.layers.Conv2D(128, 1, padding='same', use_bias=False, name='conv3')(x)
    x = tf.keras.layers.BatchNormalization(name='bn3')(x)
    x = tf.keras.layers.ReLU(max_value=6, name='relu3')(x)
    x = tf.keras.layers.MaxPooling2D(2, name='pool3')(x)

    # ===== Block 4 (Light Residual) =====
    # Skip branch
    skip = tf.keras.layers.Conv2D(128, 1, padding='same', use_bias=False, name='conv4_proj')(x)
    skip = tf.keras.layers.BatchNormalization(name='bn4_proj')(skip)

    # Main branch
    x = tf.keras.layers.DepthwiseConv2D(3, padding='same', use_bias=False, name='depthwise_conv4')(x)
    x = tf.keras.layers.Conv2D(128, 1, padding='same', use_bias=False, name='conv4')(x)
    x = tf.keras.layers.BatchNormalization(name='bn4')(x)
    x = tf.keras.layers.ReLU(max_value=6, name='relu4')(x)

    # Add skip connection
    x = tf.keras.layers.Add(name='skip_add')([x, skip])
    x = tf.keras.layers.ReLU(max_value=6, name='relu4b')(x)

    # ===== Head =====
    x = tf.keras.layers.GlobalAveragePooling2D(name='gap')(x)
    x = tf.keras.layers.Dense(64, use_bias=False, name='fc1')(x)
    x = tf.keras.layers.BatchNormalization(name='bn_fc1')(x)
    x = tf.keras.layers.ReLU(max_value=6, name='relu_fc1')(x)
    x = tf.keras.layers.Dropout(0.5, name='drop1')(x)
    outputs = tf.keras.layers.Dense(1, use_bias=True, name='output')(x)

    return tf.keras.Model(inputs, outputs, name="full_precision_model")

